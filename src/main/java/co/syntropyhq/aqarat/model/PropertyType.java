package co.syntropyhq.aqarat.model;

public class PropertyType {

    private int id;
    private String name;

    public PropertyType() {
    }

    public int getId() {
        return id;
    }

    public void setId(int id) {
        this.id = id;
    }

    public String getName() {
        return name;
    }

    public void setName(String name) {
        this.name = name;
    }
}
