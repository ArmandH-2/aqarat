"""
Stratified analysis of the AVM evaluation output.

Reads docs/evaluation/avm-predictions.csv (written by AvmEvaluation) and answers the
question the headline ratio study raises: the ten worst predictions all have zero
comparables, so how much of the error is the regression-only path?

Writes docs/evaluation/avm-stratified.md.

    python docs/evaluation/analyse.py
"""
import csv
import statistics as st
from pathlib import Path

HERE = Path(__file__).resolve().parent
PRED = HERE / "avm-predictions.csv"
OUT = HERE / "avm-stratified.md"


def load():
    rows = []
    with PRED.open(newline="", encoding="utf-8") as f:
        for r in csv.DictReader(f):
            rows.append({
                "id": int(r["property_id"]),
                "deal": r["deal_type"],
                "district": r["district"].strip(),
                "area": float(r["area_sqm"]),
                "beds": int(r["bedrooms"]),
                "actual": float(r["actual"]),
                "est": float(r["estimated"]),
                "lo": float(r["lower_bound"]),
                "hi": float(r["upper_bound"]),
                "ratio": float(r["ratio"]),
                "ape": float(r["abs_pct_error"]),
                "inside": r["inside_range"] == "true",
                "comps": int(r["comparables"]),
                "flag": r["flag"],
                "half_width_pct": 100.0 * ((float(r["upper_bound"]) - float(r["lower_bound"])) / 2.0)
                                  / float(r["estimated"]),
            })
    return rows


def stats(sample):
    """The subset of the IAAO ratio study that a stratum can support."""
    if not sample:
        return None
    n = len(sample)
    ratios = sorted(x["ratio"] for x in sample)
    med = st.median(ratios)
    mean_ratio = st.fmean(ratios)
    wmr = sum(x["est"] for x in sample) / sum(x["actual"] for x in sample)
    cod = 100.0 * st.fmean([abs(x["ratio"] - med) for x in sample]) / med
    apes = [x["ape"] for x in sample]
    return {
        "n": n,
        "median_ratio": med,
        "cod": cod,
        "prd": mean_ratio / wmr,
        "mdape": st.median(apes),
        "mape": st.fmean(apes),
        "pe10": 100.0 * sum(1 for a in apes if a <= 10) / n,
        "pe25": 100.0 * sum(1 for a in apes if a <= 25) / n,
        "coverage": 100.0 * sum(1 for x in sample if x["inside"]) / n,
        "p90": sorted(apes)[int(0.9 * n)] if n > 1 else apes[0],
        "worst": max(apes),
        "band": st.median([x["half_width_pct"] for x in sample]),
    }


def table(out, title, groups, note=None):
    out.append(f"### {title}\n")
    if note:
        out.append(note + "\n")
    out.append("| Stratum | n | Median ratio | COD % | MdAPE % | MAPE % | PE10 % | PE25 % | "
               "In range % | Median band ±% | 90th pct error % |")
    out.append("|---|---|---|---|---|---|---|---|---|---|---|")
    for label, sample in groups:
        s = stats(sample)
        if s is None:
            out.append(f"| {label} | 0 | — | — | — | — | — | — | — | — | — |")
            continue
        out.append(
            f"| {label} | {s['n']} | {s['median_ratio']:.4f} | {s['cod']:.2f} | "
            f"{s['mdape']:.2f} | {s['mape']:.2f} | {s['pe10']:.1f} | {s['pe25']:.1f} | "
            f"{s['coverage']:.1f} | {s['band']:.1f} | {s['p90']:.1f} |")
    out.append("")


def main():
    rows = load()
    out = []
    out.append("# AVM evaluation — stratified analysis\n")
    out.append("Generated by `docs/evaluation/analyse.py` from `avm-predictions.csv`.\n")
    out.append("The headline ratio study reports a COD of 21.5%, outside the IAAO residential")
    out.append("acceptance band, while every one of the ten worst predictions has zero")
    out.append("comparables. This file separates the two estimation paths to establish whether")
    out.append("that association holds across the whole sample or only in the tail.\n")

    with_comps = [r for r in rows if r["comps"] > 0]
    without = [r for r in rows if r["comps"] == 0]

    table(out, "By comparable availability",
          [("Comparables available (>=1)", with_comps),
           ("No comparable (regression or district fallback only)", without),
           ("All subjects", rows)],
          "The decisive split. A subject with at least one comparable is valued from a "
          "weighted median of adjusted like-for-like prices blended with the regression; "
          "a subject with none falls through to the regression alone, or to the district "
          "average when even that cannot be fitted.")

    table(out, "By comparable count",
          [(f"{k} comparable{'s' if k != 1 else ''}",
            [r for r in rows if r["comps"] == k]) for k in range(0, 5)])

    table(out, "By deal type",
          [("SALE", [r for r in rows if r["deal"] == "SALE"]),
           ("RENT", [r for r in rows if r["deal"] == "RENT"])])

    areas = sorted(r["area"] for r in rows)
    q1, q2, q3 = (areas[len(areas) // 4], st.median(areas), areas[3 * len(areas) // 4])
    table(out, "By area quartile",
          [(f"Q1  area <= {q1:.0f} m2", [r for r in rows if r["area"] <= q1]),
           (f"Q2  {q1:.0f} < area <= {q2:.0f} m2", [r for r in rows if q1 < r["area"] <= q2]),
           (f"Q3  {q2:.0f} < area <= {q3:.0f} m2", [r for r in rows if q2 < r["area"] <= q3]),
           (f"Q4  area > {q3:.0f} m2", [r for r in rows if r["area"] > q3])],
          f"Quartile boundaries: {q1:.0f}, {q2:.0f} and {q3:.0f} m2.")

    # Districts carrying enough subjects to say anything about.
    by_district = {}
    for r in rows:
        by_district.setdefault(r["district"], []).append(r)
    ranked = sorted(((d, s) for d, s in by_district.items() if len(s) >= 10),
                    key=lambda kv: st.median([x["ape"] for x in kv[1]]))
    table(out, "By district (10 or more subjects)", [(d, s) for d, s in ranked],
          f"{len(ranked)} of {len(by_district)} districts carry ten or more CLOSED "
          "properties. The rest are omitted as too thin to read.")

    out.append("## Findings\n")
    a, b = stats(with_comps), stats(without)
    ratio_mdape = b["mdape"] / a["mdape"]
    out.append(
        f"1. **Comparable availability is the dominant error term.** With at least one "
        f"comparable the median absolute percentage error is **{a['mdape']:.2f}%**; with none "
        f"it is **{b['mdape']:.2f}%** — {ratio_mdape:.1f} times higher. "
        f"COD moves from **{a['cod']:.2f}%** to **{b['cod']:.2f}%**, which takes the "
        f"comparables-backed stratum "
        f"{'inside' if a['cod'] <= 15 else 'closer to'} the IAAO residential acceptance "
        f"band of 5-15%.")
    by_count = [(k, stats([r for r in rows if r["comps"] == k])) for k in range(0, 5)]
    cod_series = " to ".join(f"{s['cod']:.2f}%" for _, s in by_count if s)
    pe25_series = " to ".join(f"{s['pe25']:.1f}%" for _, s in by_count if s)
    out.append(
        f"2. **The relationship is monotonic, not merely present.** Taking the subjects by "
        f"exact comparable count from zero to four, COD falls {cod_series} and PE25 rises "
        f"{pe25_series}. Every additional like-for-like transaction improves both uniformity "
        f"and accuracy, and at four comparables COD reaches "
        f"**{by_count[4][1]['cod']:.2f}%** — the strong end of the IAAO 5-15% band — on "
        f"{by_count[4][1]['n']} subjects. The sample at four is small and the estimate "
        f"correspondingly uncertain, but the direction across all five strata is unambiguous.")
    out.append(
        f"3. **What the comparables arm corrects is dispersion, not central tendency.** "
        f"The two strata have almost the same median ratio "
        f"({a['median_ratio']:.4f} with comparables against {b['median_ratio']:.4f} without), "
        f"so the regression is not systematically over- or under-valuing on average. "
        f"It is the spread that differs: MAPE of {b['mape']:.2f}% against {a['mape']:.2f}%, "
        f"and a 90th-percentile error of {b['p90']:.1f}% against {a['p90']:.1f}%. "
        f"The regression gets the middle of the distribution right and the individual "
        f"property wrong, which is exactly the failure mode a like-for-like comparison "
        f"exists to prevent. The largest quartile of properties is where this is most "
        f"visible.")
    out.append(
        f"4. **The interval is well calibrated, and it buys that with width.** Coverage of "
        f"the published range is **{a['coverage']:.1f}%** with comparables and "
        f"**{b['coverage']:.1f}%** without, against point-estimate PE25 of "
        f"**{a['pe25']:.1f}%** and **{b['pe25']:.1f}%**. Coverage that high should not be "
        f"read as accuracy: the median half-width is **±{a['band']:.0f}%** with comparables "
        f"and **±{b['band']:.0f}%** without. `rangeHalfWidth` never publishes a band "
        f"narrower than the 20% market threshold and multiplies it by up to three as "
        f"comparables run out, so a subject with no comparable is shown a range of "
        f"±60% — on a $180,000 property, $72,000 to $288,000. That is an honest "
        f"statement of uncertainty and a nearly useless one for a pricing decision. "
        f"The band narrows to ±{by_count[4][1]['band']:.0f}% at four comparables while "
        f"coverage holds at {by_count[4][1]['coverage']:.0f}%, which is where the interval "
        f"starts to be worth reading.")
    flags = {}
    for k in range(0, 5):
        sub = [r for r in rows if r["comps"] == k]
        flags[k] = {f: sum(1 for r in sub if r["flag"] == f)
                    for f in ("OK", "ABOVE_MARKET", "IMPLAUSIBLE")}
    above_total = sum(v["ABOVE_MARKET"] for v in flags.values())
    out.append("")
    out.append("### Flag distribution by comparable count\n")
    out.append("| Comparables | OK | ABOVE_MARKET | IMPLAUSIBLE | Band ±% | "
               "Window left for ABOVE_MARKET |")
    out.append("|---|---|---|---|---|---|")
    for k in range(0, 5):
        sub = [r for r in rows if r["comps"] == k]
        if not sub:
            continue
        band = stats(sub)["band"]
        window = max(0.0, 60.0 - band)
        out.append(f"| {k} | {flags[k]['OK']} | {flags[k]['ABOVE_MARKET']} | "
                   f"{flags[k]['IMPLAUSIBLE']} | {band:.0f} | "
                   f"{window:.0f} percentage points |")
    out.append("")
    out.append(
        f"5. **The ABOVE_MARKET verdict is very nearly unreachable, and the mechanism is "
        f"structural.** Across all {len(rows)} subjects the flag is raised "
        f"**{above_total} time**. The cause is visible in the table above: "
        f"`computeFlag` returns ABOVE_MARKET only for an asking price that is outside the "
        f"published band but within `implausible_threshold_percent` of the estimate. That "
        f"threshold is 60%, and `rangeHalfWidth` widens the band toward ±60% as comparables "
        f"run out — so the two boundaries converge and the middle verdict is squeezed to "
        f"nothing. At zero comparables the window is exactly zero percentage points wide. "
        f"The two settings were chosen independently and interact in a way neither "
        f"anticipates.\n\n"
        f"   Two honest qualifications. First, this sample is CLOSED properties, whose "
        f"`asking_price` is the price they closed at, so it sits near the estimate by "
        f"construction; the flag distribution here is not what a queue of live submissions "
        f"would show. Second, the finding that survives that caveat is the geometric one, "
        f"which does not depend on the sample at all: whenever the band half-width reaches "
        f"the implausibility threshold, ABOVE_MARKET cannot be returned for any asking "
        f"price whatsoever. The defect is in the interaction of two configuration values, "
        f"and the fix is to derive the implausibility threshold from the band rather than "
        f"to set it independently.")
    out.append(
        f"6. **Sample sparsity, not model form, is the binding constraint.** "
        f"{100.0 * len(without) / len(rows):.1f}% of subjects have no comparable at all "
        f"because only {len(rows)} properties in the seed are CLOSED, spread across "
        f"{len(by_district)} districts, several property types and two deal types, "
        f"then narrowed again by the plus-or-minus 30% area band. The fix is more closed "
        f"transactions, not a different estimator.")
    out.append("")

    OUT.write_text("\n".join(out), encoding="utf-8")
    print(f"Wrote {OUT}")
    print(f"  with comparables: n={a['n']} MdAPE={a['mdape']:.2f}% COD={a['cod']:.2f}%")
    print(f"  without:          n={b['n']} MdAPE={b['mdape']:.2f}% COD={b['cod']:.2f}%")


if __name__ == "__main__":
    main()
